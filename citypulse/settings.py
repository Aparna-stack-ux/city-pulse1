# Database
# https://docs.djangoproject.com/en/6.0/ref/settings/#databases

database_url = config('DATABASE_URL', default='').strip()
if database_url:
    parsed_database_url = urlparse(database_url)
    if parsed_database_url.scheme not in {'postgres', 'postgresql'}:
        raise ImproperlyConfigured('DATABASE_URL must use postgres:// or postgresql://.')
    if not parsed_database_url.hostname or not parsed_database_url.path.strip('/'):
        raise ImproperlyConfigured('DATABASE_URL must include a host and database name.')

    try:
        database_port = parsed_database_url.port
    except ValueError as error:
        raise ImproperlyConfigured('DATABASE_URL contains an invalid port.') from error

    database_options = parse_qs(parsed_database_url.query)
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': unquote(parsed_database_url.path.lstrip('/')),
            'USER': unquote(parsed_database_url.username or ''),
            'PASSWORD': unquote(parsed_database_url.password or ''),
            'HOST': parsed_database_url.hostname,
            'PORT': database_port or '',
            'OPTIONS': {
                'sslmode': database_options.get('sslmode', ['require'])[0],
            },
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


